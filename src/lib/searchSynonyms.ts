/** 질문 안에서 별칭을 빠르게 찾기 위한 역색인 (별칭 → 그룹 인덱스) */
const ALIAS_INDEX: Map<string, number> = (() => {
  const m = new Map<string, number>();
  SYNONYM_GROUPS.forEach((group, gi) => {
    group.forEach((word) => {
      // 공백 제거한 형태로 색인(띄어쓰기 흔들림 흡수: "정책 자금" → "정책자금")
      m.set(word.replace(/\s/g, "").toLowerCase(), gi);
    });
  });
  return m;
})();

/**
 * 질문(query)을 받아, 포함된 동의어 그룹의 모든 정식 용어를 뒤에 덧붙여 반환합니다.
 * (원문은 그대로 유지 + 확장어 append → 검색 점수 계산이 놓치지 않게 함)
 *
 * 예) expandQuery("보조금 어디서 받나요")
 *     → "보조금 어디서 받나요 정부지원사업 정부지원 정부지원금 지원사업 지원금 보조금 정부보조금 국가지원 나라지원"
 */
export function expandQuery(query: string): string {
  if (!query) return query;
  const compact = query.replace(/\s/g, "").toLowerCase();
  const matchedGroups = new Set<number>();

  // 1) 질문의 '공백 제거 전체 문자열' 안에 별칭이 부분 포함되는지 검사
  //    (띄어쓰기 흔들림·조사 결합을 흡수: "정책자금은", "정책 자금이" 모두 인식)
  ALIAS_INDEX.forEach((gi, alias) => {
    if (compact.includes(alias)) matchedGroups.add(gi);
  });

  if (matchedGroups.size === 0) return query;

  const expansions: string[] = [];
  matchedGroups.forEach((gi) => {
    SYNONYM_GROUPS[gi].forEach((w) => expansions.push(w));
  });

  return `${query} ${expansions.join(" ")}`;
}
